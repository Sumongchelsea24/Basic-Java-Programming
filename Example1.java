public class Example1 {

  public static void main(String[] args) {
    //Relational Operators -> ==,!=,<,>,<=,>=
      
    int a = 5;
    int b = 10;

    boolean c = (a == b);
    System.out.println(c);//false

    boolean d = (a != b);
    System.out.print(d);//true

    boolean e = (a < b);//true
    System.out.println(e);
    
    boolean f = (a <= b);//true
    System.out.println(f);
  }
  
}
